// Altitude interpolee (m) a une distance donnee, en km carnet.
export function altAt(km) {
  const p = PROFIL.points;
  if (km <= 0) return p[0][1];
  if (km >= PROFIL.kmTotal) return p[p.length - 1][1];
  const pas = PROFIL.kmTotal / (p.length - 1);
  const i = Math.min(p.length - 2, Math.floor(km / pas));
  const t = (km - p[i][0]) / (p[i + 1][0] - p[i][0]);
  return p[i][1] + (p[i + 1][1] - p[i][1]) * t;
}
