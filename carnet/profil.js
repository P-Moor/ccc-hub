/** Altitude interpolee a un kilometre donne. */
export function altAt(km) {
  const p = PROFIL.points;
  if (km <= p[0][0]) return p[0][1];
  for (let i = 1; i < p.length; i++) {
    if (km <= p[i][0]) {
      const a = p[i - 1], b = p[i];
      const t = (km - a[0]) / ((b[0] - a[0]) || 1);
      return Math.round(a[1] + (b[1] - a[1]) * t);
    }
  }
  return p[p.length - 1][1];
}

